def self_check():
    """预埋风险自检：每个风险关键词必须真实出现在数据中。"""
    all_text = "\n".join(written_texts)
    missing = [k for k, kw in PLANTED_RISKS.items() if kw not in all_text]
    if missing:
        raise SystemExit(f"[FAIL] 预埋风险未写入数据: {missing}")
    print("[OK] 预埋风险自检通过:", ", ".join(PLANTED_RISKS))


